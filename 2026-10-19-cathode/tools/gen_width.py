#!/usr/bin/env python3
"""Generate src/width_table.rs from the Unicode Character Database bundled in Python.

ZERO: general category Mn/Me/Cf (minus U+00AD soft hyphen, which terminals draw),
      plus Hangul Jamo medial vowels / final consonants (U+1160..U+11FF) like wcwidth(3).
WIDE: East Asian Width W or F (this already covers Emoji_Presentation).
"""
import sys, unicodedata

def ranges(pred):
    out, start, prev = [], None, None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
            prev = cp
        elif start is not None:
            out.append((start, prev)); start = None
    if start is not None:
        out.append((start, prev))
    return out

def zero(cp):
    if cp == 0xAD or cp < 0x20 or 0x7F <= cp < 0xA0:
        return False
    if 0x1160 <= cp <= 0x11FF:
        return True
    return unicodedata.category(chr(cp)) in ("Mn", "Me", "Cf")

def wide(cp):
    return unicodedata.east_asian_width(chr(cp)) in ("W", "F")

def emit(name, rs):
    s = f"pub static {name}: [(u32, u32); {len(rs)}] = [\n"
    for i in range(0, len(rs), 6):
        s += "    " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in rs[i:i+6]) + "\n"
    return s + "];\n"

with open(sys.argv[1], "w") as f:
    f.write(f"// @generated by tools/gen_width.py from Unicode {unicodedata.unidata_version}. Do not edit.\n")
    f.write(emit("ZERO", ranges(zero)))
    f.write(emit("WIDE", ranges(wide)))
