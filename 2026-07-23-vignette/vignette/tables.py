def size_category(value):
    """JPEG 'SSSS' size category: number of bits needed to represent the
    magnitude of `value` (0 has category 0)."""
    value = abs(value)
    n = 0
    while value:
        n += 1
        value >>= 1
    return n


def encode_magnitude(value, size):
    """The JPEG variable-length-integer encoding for DC diffs / AC values:
    for value >= 0, the `size`-bit binary representation; for value < 0,
    the one's complement of the binary representation of -value."""
    if size == 0:
        return 0
    if value < 0:
        value = value - 1  # one's complement trick: (value-1) & mask
    return value & ((1 << size) - 1)


def decode_magnitude(bits, size):
    """Inverse of encode_magnitude."""
    if size == 0:
        return 0
    if bits < (1 << (size - 1)):
        return bits - (1 << size) + 1
    return bits
