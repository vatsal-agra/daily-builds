def scale_quant_table(base, quality):
    """The IJG (libjpeg) quality->quantization-table scaling formula.
    quality in [1,100]; 100 = highest quality/least compression."""
    quality = max(1, min(100, int(quality)))
    if quality < 50:
        scale = 5000 // quality if quality > 0 else 5000
    else:
        scale = 200 - quality * 2
    out = []
    for v in base:
        t = (v * scale + 50) // 100
        t = max(1, min(255, t))
        out.append(t)
    return out


