_PLACEHOLDER = ["......", ".####.", "#....#", "#....#", "#....#", ".####.", "......"]


def _parse(rows):
    bitmap = []
    for row in rows:
        bitmap.append([c == "#" for c in row])
    bitmap.append([False] * GLYPH_W)  # line-gap row
    return bitmap


_BITMAPS = {ch: _parse(rows) for ch, rows in _GLYPHS_RAW.items()}
_PLACEHOLDER_BITMAP = _parse(_PLACEHOLDER)


def glyph_bitmap(ch):
    """Return the GLYPH_H x GLYPH_W boolean bitmap for `ch` (space -> blank)."""
    if ch == " " or ch == "\t":
        return _parse([" " * GLYPH_W] * 7)
    if ch in _BITMAPS:
        return _BITMAPS[ch]
    upper = ch.upper()
    if upper in _BITMAPS:
        return _BITMAPS[upper]
    return _PLACEHOLDER_BITMAP


def advance_width(font_size_px):
    """Monospace advance width (px) for one character at `font_size_px`."""
    scale = font_size_px / GLYPH_H
    return GLYPH_W * scale


def cell_height(font_size_px):
    return font_size_px
