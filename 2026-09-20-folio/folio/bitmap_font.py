def glyph_for(char):
    """Return a list of 7 strings (5 chars each) of '#'/'.' for `char`."""
    if char in _FONT:
        return _FONT[char]
    upper = char.upper()
    if upper in _FONT:
        return _FONT[upper]
    return _FALLBACK
