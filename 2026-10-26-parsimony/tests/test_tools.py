def load_generated(code):
    d = tempfile.mkdtemp()
    path = os.path.join(d, "gen_parser.py")
    with open(path, "w") as f:
        f.write(code)
    spec = importlib.util.spec_from_file_location("gen_parser", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod, path


class Codegen(unittest.TestCase):
    CASES = {
        "json.pg": ['{"a":[1,2.5e3,{"b":null}],"c":[true,false]}', "[]", "{}", '[1,]', '{"a" 1}'],
        "expr.pg": ["1+2*3", "(1+2)*-3^2", "2^3^2", "1 +", "1 $ 2"],
        "ll1_lists.pg": ["x = 1 + 2; print (x) * 3;", "", "x = ;"],
        "slr_fails.pg": ["a = b", "*a = **b", "= a"],
    }

    def test_generated_parser_matches_in_process_parser(self):
        for name, inputs in self.CASES.items():
            L = example(name)
            mod, _ = load_generated(generate(L, "lalr"))
            for src in inputs:
                with self.subTest(grammar=name, src=src):
                    try:
                        want = L.parse(src, "lalr").sexp()
                    except (ParseError, LexError) as e:
                        with self.assertRaises(mod.ParseError) as cm:
                            mod.parse(src)
                        self.assertEqual(str(cm.exception).split(": ", 1)[-1].split("; expected")[0].split(": ", 1)[-1],
                                         str(e).split(": ", 1)[-1].split("; expected")[0].split(": ", 1)[-1])
                    else:
                        self.assertEqual(mod.parse(src).sexp(), want)

    def test_generated_module_is_standalone_and_runnable(self):
        code = generate(example("expr.pg"))
        self.assertNotIn("parsimony", code.replace("Generated by Parsimony", ""))
        _, path = load_generated(code)
        r = subprocess.run([sys.executable, "-I", path, "1+2"], capture_output=True, text=True, cwd=tempfile.gettempdir())
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(r.stdout.strip(), "(expr (expr NUM:1) + (expr NUM:2))")
        r = subprocess.run([sys.executable, "-I", path, "1+"], capture_output=True, text=True, cwd=tempfile.gettempdir())
        self.assertEqual(r.returncode, 1)
        self.assertIn("syntax error at 1:3", r.stderr)

    def test_conflicted_grammar_warns_in_header(self):
        self.assertIn("WARNING", generate(example("dangling_else.pg")))

    def test_every_lr_method_generates(self):
        L = example("json.pg")
        for m in METHODS:
            mod, _ = load_generated(generate(L, m))
            self.assertEqual(mod.parse("[1,2]").sexp(), L.parse("[1,2]", "lalr").sexp(), m)


class Witness(unittest.TestCase):
    def test_dangling_else(self):
        w = find_ambiguity(example("dangling_else.pg").grammar)
        self.assertEqual(w.text(), "if ID then if ID then ID else ID")
        self.assertEqual(w.parses, 2)
        self.assertEqual(len({t.sexp() for t in w.trees}), 2)

    def test_expression_ambiguity(self):
        self.assertEqual(find_ambiguity(example("ambiguous.pg").grammar).text(), "n + n + n")

    def test_unambiguous_grammars_yield_nothing(self):
        for f in ("json.pg", "ll1_lists.pg", "slr_fails.pg", "lr1_not_lalr.pg", "dangling_else_fixed.pg"):
            if f == "dangling_else_fixed.pg":
                continue          # still ambiguous as a *grammar*; precedence only resolves the parser
            self.assertIsNone(find_ambiguity(example(f).grammar, max_len=8), f)

    def test_empty_sentence_witness(self):
        w = find_ambiguity(example("nullable.pg").grammar)
        self.assertIn("empty", w.text())


class Fuzz(unittest.TestCase):
    """Differential fuzzing with Earley as the oracle (see REVIEW.md)."""
    T, N = ["a", "b", "c"], ["S", "A", "B"]

    def rand_grammar(self, rnd):
        lines = []
        for nt in self.N:
            alts = [" ".join(rnd.choice(["'%s'" % t for t in self.T] + self.N)
                             for _ in range(rnd.choice([0, 1, 1, 2, 2, 3])))
                    for _ in range(rnd.randint(1, 3))]
            lines.append(f"{nt} : " + " | ".join(alts) + " ;")
        return "\n".join(lines)

    def accepts(self, f, s):
        try:
            f(s); return True
        except (ParseError, LexError):
            return False

    def test_lr_family_agrees_with_earley(self):
        rnd = random.Random(20261026)
        strings = ["".join(p) for n in range(6) for p in itertools.product("abc", repeat=n)]
        graded = 0
        for _ in range(120):
            src = self.rand_grammar(rnd)
            L = Language(src)
            if "S" in L.analysis.non_productive():
                continue
            ok = {m: not L.table(m).conflicts for m in ("slr", "lalr", "lr1")}
            self.assertTrue(not ok["slr"] or ok["lalr"], src)          # SLR ⊆ LALR ⊆ LR(1)
            self.assertTrue(not ok["lalr"] or ok["lr1"], src)
            if not ok["lr1"]:
                continue
            graded += 1
            for s in strings:
                want = self.accepts(L.earley, s)
                for m in ("slr", "lalr", "lr1"):
                    if ok[m]:
                        self.assertEqual(self.accepts(lambda x: L.parse(x, m), s), want, (src, m, s))
                if want:
                    r = L.earley(s)
                    self.assertEqual(r.count(), 1, (src, s))            # LR(1) ⇒ unambiguous
                    self.assertEqual(r.trees(1)[0], L.parse(s, "lr1"), (src, s))
        self.assertGreater(graded, 30)


class CLI(unittest.TestCase):
    def run_cli(self, *args, stdin=None):
        return subprocess.run([sys.executable, "-m", "parsimony", *args], capture_output=True, text=True,
                              cwd=ROOT, input=stdin)

    def ex(self, n): return os.path.join(EX, n)

    def test_parse_ok_and_error_exit_codes(self):
        r = self.run_cli("parse", self.ex("expr.pg"), "-e", "1+2", "--format", "sexp")
        self.assertEqual((r.returncode, r.stdout.strip()), (0, "(expr (expr NUM:1) + (expr NUM:2))"))
        r = self.run_cli("parse", self.ex("expr.pg"), "-e", "1+")
        self.assertEqual(r.returncode, 1)
        self.assertIn("syntax error at 1:3", r.stderr)
        r = self.run_cli("parse", self.ex("expr.pg"), "-e", "1 $")
        self.assertEqual(r.returncode, 1)

    def test_stdin_input(self):
        r = self.run_cli("parse", self.ex("expr.pg"), "--format", "sexp", stdin="3*4")
        self.assertEqual(r.returncode, 0)

    def test_grammar_error_exit_2(self):
        with tempfile.NamedTemporaryFile("w", suffix=".pg", delete=False) as f:
            f.write("s : undefined_thing ;")
        r = self.run_cli("check", f.name)
        self.assertEqual(r.returncode, 2)
        self.assertIn("grammar error", r.stderr)
        self.assertEqual(self.run_cli("check", "/no/such.pg").returncode, 2)

    def test_conflicts_exit_code_and_witness(self):
        r = self.run_cli("conflicts", self.ex("dangling_else.pg"), "-m", "lalr", "--witness")
        self.assertEqual(r.returncode, 1)
        self.assertIn("ambiguous sentence: if ID then if ID then ID else ID", r.stdout)
        self.assertEqual(self.run_cli("conflicts", self.ex("json.pg")).returncode, 0)

    def test_check_classifies(self):
        out = self.run_cli("check", self.ex("lr1_not_lalr.pg")).stdout
        self.assertIn("✘ LALR(1)", out)
        self.assertIn("✔ LR(1)", out)
        self.assertIn("smallest LR class: LR(1)", out)

    def test_ambig_and_compare_and_ll1_and_transform_and_gen(self):
        out = self.run_cli("ambig", self.ex("ambiguous.pg"), "-e", "n+n+n+n").stdout
        self.assertIn("parses: 5", out)
        out = self.run_cli("compare", self.ex("ll1_lists.pg"), "-e", "x = 1; print x;").stdout
        self.assertIn("agree on the parse tree", out)
        self.assertEqual(self.run_cli("compare", self.ex("ll1_lists.pg"), "-e", "x = ;").returncode, 0)
        self.assertEqual(self.run_cli("ll1", self.ex("expr.pg")).returncode, 1)
        out = self.run_cli("transform", self.ex("expr.pg")).stdout
        self.assertIn("expr_tail", out)
        with tempfile.TemporaryDirectory() as d:
            out_path = os.path.join(d, "p.py")
            self.assertEqual(self.run_cli("gen", self.ex("json.pg"), "-o", out_path).returncode, 0)
            self.assertTrue(os.path.getsize(out_path) > 1000)

    def test_recover_flag(self):
        r = self.run_cli("parse", self.ex("recover.pg"), "--recover", "--format", "sexp", "-e", "a = 1; b = + ; c = 2;")
        self.assertEqual(r.returncode, 1)
        self.assertEqual(r.stderr.count("syntax error"), 1)
        self.assertIn("error:+", r.stdout)

    def test_bad_flags(self):
        self.assertEqual(self.run_cli("states", self.ex("expr.pg"), "-m", "earley").returncode, 2)
        self.assertEqual(self.run_cli("parse", self.ex("expr.pg"), "-m", "nope", "-e", "1").returncode, 2)
        self.assertEqual(self.run_cli().returncode, 2)

    def test_broken_pipe_is_quiet(self):
        p = subprocess.Popen([sys.executable, "-m", "parsimony", "states", self.ex("json.pg")],
                             stdout=subprocess.PIPE, stderr=subprocess.PIPE, cwd=ROOT, text=True)
        p.stdout.readline(); p.stdout.close()
        _, err = p.communicate()
        self.assertNotIn("Traceback", err)


class SelfCheck(unittest.TestCase):
    """Parsimony's DSL, written as a Parsimony grammar, parses every grammar in examples/."""

    def test_dsl_grammar_is_lalr_and_accepts_all_examples(self):
        dsl = example("parsimony_dsl.pg")
        self.assertFalse(dsl.table("lalr").conflicts)
        files = sorted(glob.glob(os.path.join(EX, "*.pg")))
        self.assertGreaterEqual(len(files), 10)
        mod, _ = load_generated(generate(dsl, "lalr"))            # run via the *generated* parser
        for path in files:
            with self.subTest(path=os.path.basename(path)):
                with open(path, encoding="utf-8") as fh:
                    text = fh.read()
                tree = dsl.parse(text)
                self.assertEqual(mod.parse(text).sexp(), tree.sexp())
                n_rules = sum(1 for n in tree.children if n.children and n.children[0].name == "rule")
                self.assertGreater(n_rules, 0)

    def test_dsl_grammar_rejects_garbage(self):
        dsl = example("parsimony_dsl.pg")
        for bad in ["s : 'a'", "s 'a' ;", ": ;", "s : ( 'a' ;"]:
            with self.subTest(bad=bad), self.assertRaises((ParseError, LexError)):
                dsl.parse(bad)


