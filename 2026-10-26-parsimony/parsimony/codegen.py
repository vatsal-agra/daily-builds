"""Emit a standalone, dependency-free Python parser module from a built LR table."""
from __future__ import annotations

import pprint
from typing import Optional

from .api import Language
from .grammar import END

_TEMPLATE = '''#!/usr/bin/env python3
"""@@TITLE@@

Generated by Parsimony (@@METHOD@@ tables, @@NSTATES@@ states). Needs only the Python 3 standard
library. Usage:  python3 this_file.py 'input text'   |   from this_file import parse
"""
import re
import sys

END = "$end"
SKIPS = @@SKIPS@@
# (priority, token type, regex or None, literal or None); longest match wins, literals win ties
TOKENS = @@TOKENS@@
# production index -> (lhs, rhs length); index 0 is the augmented $accept rule
PRODS = @@PRODS@@
HIDDEN = @@HIDDEN@@
ACTION = @@ACTION@@
GOTO = @@GOTO@@

_SKIP_RE = [re.compile(s) for s in SKIPS]
_TOK_RE = [(p, n, re.compile(r) if r is not None else None, lit) for p, n, r, lit in TOKENS]


class ParseError(Exception):
    def __init__(self, msg, token=None, expected=()):
        super().__init__(msg)
        self.token, self.expected = token, list(expected)


class Token:
    __slots__ = ("type", "text", "line", "col")

    def __init__(self, type, text, line, col):
        self.type, self.text, self.line, self.col = type, text, line, col

    def __repr__(self):
        return "Token(%s, %r, %d:%d)" % (self.type, self.text, self.line, self.col)


class Node:
    def __init__(self, name, children):
        self.name, self.children = name, children

    def sexp(self):
        out, stack = [], [self]
        while stack:
            n = stack.pop()
            if isinstance(n, str):
                out.append(")")
            elif isinstance(n, Token):
                out.append(n.text if n.type.startswith("'") else "%s:%s" % (n.type, n.text))
            elif not n.children:
                out.append("(%s)" % n.name)
            else:
                out.append("(" + n.name)
                stack.append(")")
                stack.extend(reversed(n.children))
        return " ".join(out).replace(" )", ")")


def tokenize(text):
    out, pos, line, col, n = [], 0, 1, 1, len(text)
    while pos < n:
        best_len, best = 0, None
        for sk in _SKIP_RE:
            m = sk.match(text, pos)
            if m and m.end() - pos > best_len:
                best_len, best = m.end() - pos, None
        for prio, name, rx, lit in _TOK_RE:
            if lit is not None:
                ln = len(lit) if text.startswith(lit, pos) else 0
            else:
                m = rx.match(text, pos)
                ln = (m.end() - pos) if m else 0
            if ln > best_len or (ln == best_len and ln > 0 and best is not None and prio < best[0]):
                best_len, best = ln, (prio, name)
        if best_len == 0:
            raise ParseError("%d:%d: unexpected character %r (near %r)" % (
                line, col, text[pos], text[pos:pos + 10].split("\\n")[0]))
        if best is not None:
            out.append(Token(best[1], text[pos:pos + best_len], line, col))
        chunk = text[pos:pos + best_len]
        nl = chunk.count("\\n")
        if nl:
            line += nl
            col = len(chunk) - chunk.rfind("\\n")
        else:
            col += best_len
        pos += best_len
    out.append(Token(END, "", line, col))
    return out


def _flatten(kids):
    out, stack = [], list(reversed(kids))
    while stack:
        k = stack.pop()
        if isinstance(k, Node) and k.name in HIDDEN:
            stack.extend(reversed(k.children))
        else:
            out.append(k)
    return out


def parse(text):
    """Parse ``text``; return the parse tree (Node) or raise ParseError."""
    toks = tokenize(text)
    states, values, pos = [0], [], 0
    while True:
        tok = toks[pos]
        act = ACTION[states[-1]].get(tok.type)
        if act is None:
            exp = sorted(ACTION[states[-1]])
            got = "end of input" if tok.type == END else repr(tok.text)
            raise ParseError("syntax error at %d:%d: unexpected %s; expected one of: %s" % (
                tok.line, tok.col, got, ", ".join(e if e != END else "end of input" for e in exp)), tok, exp)
        if act[0] == "s":
            states.append(act[1]); values.append(tok); pos += 1
        elif act[0] == "r":
            lhs, k = PRODS[act[1]]
            kids = values[len(values) - k:] if k else []
            if k:
                del values[-k:]; del states[-k:]
            if lhs not in HIDDEN:
                kids = _flatten(kids)
            values.append(Node(lhs, list(kids)))
            states.append(GOTO[states[-1]][lhs])
        else:
            return values[0]


if __name__ == "__main__":
    src = sys.argv[1] if len(sys.argv) > 1 else sys.stdin.read()
    try:
        print(parse(src).sexp())
    except ParseError as e:
        print("error: %s" % e, file=sys.stderr)
        sys.exit(1)
'''


def generate(lang: Language, method: str = "lalr", title: Optional[str] = None) -> str:
    t = lang.table(method)
    if t.conflicts:
        # emit anyway (conflicts are resolved by yacc defaults) but say so loudly in the header
        warn = f"  WARNING: {len(t.conflicts)} unresolved {method.upper()} conflict(s); defaults applied.\n"
    else:
        warn = ""
    g = lang.grammar
    tokens = [(1, n, rx, None) for n, rx in g.token_regex.items()] + \
             [(0, n, None, lit) for n, lit in g.literals.items() if n not in g.token_regex]
    prods = [(p.lhs, len(p.rhs)) for p in t.prods]
    action = [{k: tuple(v) for k, v in sorted(a.items())} for a in t.action]
    goto = [dict(sorted(gt.items())) for gt in t.goto]
    fmt = lambda obj: pprint.pformat(obj, width=100, compact=True)
    code = _TEMPLATE
    for key, val in {
        "TITLE": (title or f"Standalone parser for a {len(g.productions)}-production grammar (start: {g.start}).") + ("\n" + warn.rstrip() if warn else ""),
        "METHOD": method.upper(), "NSTATES": str(t.n_states),
        "SKIPS": fmt(g.skips), "TOKENS": fmt(tokens), "PRODS": fmt(prods),
        "HIDDEN": fmt(sorted(g.hidden)), "ACTION": fmt(action), "GOTO": fmt(goto),
    }.items():
        code = code.replace(f"@@{key}@@", val)
    return code
