# Lowercase reuses the uppercase glyph shapes (documented limitation: no
# distinct lowercase forms), which keeps the hand-authored stroke table a
# manageable size while still covering every character a real page uses.
for _c in 'abcdefghijklmnopqrstuvwxyz':
    _STROKES[_c] = _STROKES[_c.upper()]

_UNKNOWN = [(0, 0, 4, 0), (4, 0, 4, 6), (4, 6, 0, 6), (0, 6, 0, 0)]

_glyph_cache = {}


def _bresenham(x0, y0, x1, y1):
    points = []
    dx = x1 - x0
    dy = y1 - y0
    steps = max(abs(dx), abs(dy), 1)
    for i in range(steps + 1):
        t = i / steps
        points.append((round(x0 + dx * t), round(y0 + dy * t)))
    return points


def glyph_pixels(ch):
    """Return a set of (x, y) grid cells that are 'on' for this character."""
    if ch in _glyph_cache:
        return _glyph_cache[ch]
    strokes = _STROKES.get(ch, _UNKNOWN if ch != ' ' else [])
    pixels = set()
    for (x0, y0, x1, y1) in strokes:
        pixels.update(_bresenham(x0, y0, x1, y1))
    _glyph_cache[ch] = pixels
    return pixels


def char_width(scale=1):
    return GLYPH_ADVANCE * scale


def measure_text(text, scale=1):
    """Width in pixels of `text` rendered at the given integer scale."""
    return len(text) * GLYPH_ADVANCE * scale


def line_height(scale=1):
    return (GLYPH_H + 2) * scale


def render_glyph(ch, scale=1):
    """Yield (x, y) pixel offsets (relative to the glyph's top-left) to fill."""
    for (gx, gy) in glyph_pixels(ch):
        for sx in range(scale):
            for sy in range(scale):
                yield (gx * scale + sx, gy * scale + sy)
