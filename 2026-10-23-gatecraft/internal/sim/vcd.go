package sim

import (
	"bufio"
	"fmt"
	"io"
	"math/big"
	"sort"
	"strings"

	"gatecraft/internal/aig"
)

// VCD writes IEEE-1364 value-change-dump waveforms (viewable in GTKWave/Surfer).
type VCD struct {
	w      *bufio.Writer
	names  []string
	ids    []string
	widths []int
	last   []*big.Int
	lastT  int
	any    bool
	clocks map[string]bool
	// Recorded for HTML waveform viewer
	Trace *Trace
}

// Trace is an in-memory record of sampled values for the HTML viewer.
type Trace struct {
	Names  []string
	Widths []int
	Times  []int
	Values [][]string // per sample, per signal: hex string
}

func NewVCD(w io.Writer) *VCD {
	return &VCD{w: bufio.NewWriter(w), clocks: map[string]bool{}, lastT: -1}
}

func vcdID(n int) string {
	const base = 94
	s := ""
	for {
		s += string(rune(33 + n%base))
		n = n/base - 1
		if n < 0 {
			break
		}
	}
	return s
}

// Header declares all named signals, grouped into module scopes by '.'.
func (v *VCD) Header(g *aig.AIG) {
	for _, l := range g.Latches {
		v.clocks[strings.SplitN(l.Clock, "[", 2)[0]] = true
	}
	names := append([]string(nil), g.NameOrder...)
	// top-level ports first for readability
	sort.SliceStable(names, func(i, j int) bool {
		di, dj := strings.Contains(names[i], "."), strings.Contains(names[j], ".")
		return !di && dj
	})
	fmt.Fprintf(v.w, "$date generated by gatecraft $end\n$version gatecraft 1.0 $end\n$timescale 1ns $end\n")
	var cur []string
	for _, n := range names {
		parts := strings.Split(n, ".")
		scope, leaf := parts[:len(parts)-1], parts[len(parts)-1]
		// close/open scopes
		common := 0
		for common < len(cur) && common < len(scope) && cur[common] == scope[common] {
			common++
		}
		for i := len(cur); i > common; i-- {
			fmt.Fprintf(v.w, "$upscope $end\n")
		}
		for i := common; i < len(scope); i++ {
			fmt.Fprintf(v.w, "$scope module %s $end\n", scope[i])
		}
		cur = scope
		w := len(g.Names[n])
		id := vcdID(len(v.names))
		v.names = append(v.names, n)
		v.ids = append(v.ids, id)
		v.widths = append(v.widths, w)
		v.last = append(v.last, nil)
		if w > 1 {
			fmt.Fprintf(v.w, "$var wire %d %s %s [%d:0] $end\n", w, id, leaf, w-1)
		} else {
			fmt.Fprintf(v.w, "$var wire 1 %s %s $end\n", id, leaf)
		}
	}
	for i := len(cur); i > 0; i-- {
		fmt.Fprintf(v.w, "$upscope $end\n")
	}
	fmt.Fprintf(v.w, "$enddefinitions $end\n")
	v.Trace = &Trace{Names: v.names, Widths: v.widths}
}

// Sample records changed values at time t. clkHigh forces clock inputs to 1.
func (v *VCD) Sample(s *Sim, t int, clkHigh bool) {
	if t <= v.lastT && v.any {
		t = v.lastT // never go backwards
	}
	var changes []string
	row := make([]string, len(v.names))
	for i, n := range v.names {
		val := s.bits(s.G.Names[n])
		if v.clocks[n] && v.widths[i] == 1 {
			val = new(big.Int)
			if clkHigh {
				val.SetInt64(1)
			}
		}
		row[i] = val.Text(16)
		if v.last[i] != nil && v.last[i].Cmp(val) == 0 {
			continue
		}
		v.last[i] = val
		if v.widths[i] == 1 {
			changes = append(changes, fmt.Sprintf("%s%s", val.Text(2), v.ids[i]))
		} else {
			changes = append(changes, fmt.Sprintf("b%s %s", val.Text(2), v.ids[i]))
		}
	}
	if len(changes) == 0 && v.any {
		return
	}
	if t != v.lastT || !v.any {
		fmt.Fprintf(v.w, "#%d\n", t)
	}
	if !v.any {
		fmt.Fprintf(v.w, "$dumpvars\n")
	}
	for _, c := range changes {
		fmt.Fprintf(v.w, "%s\n", c)
	}
	if !v.any {
		fmt.Fprintf(v.w, "$end\n")
	}
	v.any = true
	v.lastT = t
	v.Trace.Times = append(v.Trace.Times, t)
	v.Trace.Values = append(v.Trace.Values, row)
}

func (v *VCD) Close() { v.w.Flush() }
