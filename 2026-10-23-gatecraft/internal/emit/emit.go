// Package emit writes an AIG as structural Verilog, BLIF or ASCII AIGER, and
// reads AIGER back so external benchmark circuits can be analysed.
package emit

import (
	"bufio"
	"fmt"
	"io"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"gatecraft/internal/aig"
)

var nonIdent = regexp.MustCompile(`[^A-Za-z0-9_]`)

func ident(s string) string {
	s = nonIdent.ReplaceAllString(s, "_")
	if s == "" || (s[0] >= '0' && s[0] <= '9') {
		s = "_" + s
	}
	return s
}

// piName names an input bit.
func piName(g *aig.AIG, pi aig.PI) string {
	if p := g.FindInput(pi.Port); p != nil && len(p.Bits) > 1 {
		return fmt.Sprintf("%s[%d]", pi.Port, pi.Bit)
	}
	return pi.Port
}

// Verilog writes a structural Verilog module equivalent to g.
func Verilog(w io.Writer, g *aig.AIG, module string) error {
	bw := bufio.NewWriter(w)
	live := g.Live()
	liveL := g.LiveLatches()
	clocks := map[string]bool{}
	for i, l := range g.Latches {
		if liveL[i] {
			clocks[l.Clock] = true
		}
	}
	inputNames := map[string]bool{}
	for _, p := range g.Inputs {
		inputNames[p.Name] = true
	}
	var ports []string
	for _, p := range g.Inputs {
		ports = append(ports, decl("input", p.Name, len(p.Bits)))
	}
	for _, p := range g.Outputs {
		ports = append(ports, decl("output", p.Name, len(p.Bits)))
	}
	fmt.Fprintf(bw, "// generated by gatecraft: %s\n", g.Stats())
	fmt.Fprintf(bw, "module %s(\n  %s\n);\n", module, strings.Join(ports, ",\n  "))
	name := func(id uint32) string {
		n := g.Nodes[id]
		switch n.Kind {
		case aig.KConst:
			return "1'b0"
		case aig.KInput:
			return piName(g, g.PIs[n.Idx])
		case aig.KLatch:
			return fmt.Sprintf("r%d", n.Idx)
		}
		return fmt.Sprintf("n%d", id)
	}
	ref := func(l aig.Lit) string {
		if l == aig.False {
			return "1'b0"
		}
		if l == aig.True {
			return "1'b1"
		}
		s := name(l.ID())
		if l.Neg() {
			return "~" + s
		}
		return s
	}
	for i, l := range g.Latches {
		if liveL[i] {
			iv := 0
			if l.Init {
				iv = 1
			}
			fmt.Fprintf(bw, "  reg r%d = 1'b%d; // %s\n", i, iv, l.Name)
		}
	}
	for id, n := range g.Nodes {
		if n.Kind == aig.KAnd && live[id] {
			fmt.Fprintf(bw, "  wire n%d = %s & %s;\n", id, ref(n.A), ref(n.B))
		}
	}
	for _, p := range g.Outputs {
		for i, b := range p.Bits {
			if len(p.Bits) == 1 {
				fmt.Fprintf(bw, "  assign %s = %s;\n", p.Name, ref(b))
			} else {
				fmt.Fprintf(bw, "  assign %s[%d] = %s;\n", p.Name, i, ref(b))
			}
		}
	}
	var cs []string
	for c := range clocks {
		cs = append(cs, c)
	}
	sort.Strings(cs)
	for _, c := range cs {
		fmt.Fprintf(bw, "  always @(posedge %s) begin\n", c)
		for i, l := range g.Latches {
			if liveL[i] && l.Clock == c {
				fmt.Fprintf(bw, "    r%d <= %s;\n", i, ref(l.D))
			}
		}
		fmt.Fprintf(bw, "  end\n")
	}
	for i, p := range g.Asserts {
		fmt.Fprintf(bw, "  %s: assert property (%s);\n", ident(fmt.Sprintf("a%d_%s", i, p.Name)), ref(p.Lit))
	}
	for i, p := range g.Assumes {
		fmt.Fprintf(bw, "  %s: assume property (%s);\n", ident(fmt.Sprintf("m%d_%s", i, p.Name)), ref(p.Lit))
	}
	fmt.Fprintf(bw, "endmodule\n")
	return bw.Flush()
}

func decl(dir, name string, w int) string {
	if w == 1 {
		return fmt.Sprintf("%s %s", dir, name)
	}
	return fmt.Sprintf("%s [%d:0] %s", dir, w-1, name)
}

// BLIF writes the AIG as a BLIF network of 2-input .names plus .latch lines.
func BLIF(w io.Writer, g *aig.AIG, model string) error {
	bw := bufio.NewWriter(w)
	live := g.Live()
	liveL := g.LiveLatches()
	fmt.Fprintf(bw, ".model %s\n.inputs", model)
	for _, pi := range g.PIs {
		fmt.Fprintf(bw, " %s", piName(g, pi))
	}
	fmt.Fprintf(bw, "\n.outputs")
	outNames := []string{}
	for _, p := range g.Outputs {
		for i := range p.Bits {
			n := p.Name
			if len(p.Bits) > 1 {
				n = fmt.Sprintf("%s[%d]", p.Name, i)
			}
			outNames = append(outNames, n)
			fmt.Fprintf(bw, " %s", n)
		}
	}
	fmt.Fprintln(bw)
	name := func(id uint32) string {
		n := g.Nodes[id]
		switch n.Kind {
		case aig.KInput:
			return piName(g, g.PIs[n.Idx])
		case aig.KLatch:
			return fmt.Sprintf("r%d", n.Idx)
		case aig.KConst:
			return "zero"
		}
		return fmt.Sprintf("n%d", id)
	}
	fmt.Fprintf(bw, ".names zero\n")
	for i, l := range g.Latches {
		if liveL[i] {
			iv := 0
			if l.Init {
				iv = 1
			}
			// D is always routed through a named net for simplicity
			fmt.Fprintf(bw, ".latch d%d r%d re %s %d\n", i, i, l.Clock, iv)
		}
	}
	// a net carrying (possibly inverted) literal l
	buf := func(dst string, l aig.Lit) {
		switch l {
		case aig.False:
			fmt.Fprintf(bw, ".names %s\n", dst)
		case aig.True:
			fmt.Fprintf(bw, ".names %s\n1\n", dst)
		default:
			if l.Neg() {
				fmt.Fprintf(bw, ".names %s %s\n0 1\n", name(l.ID()), dst)
			} else {
				fmt.Fprintf(bw, ".names %s %s\n1 1\n", name(l.ID()), dst)
			}
		}
	}
	for id, n := range g.Nodes {
		if n.Kind == aig.KAnd && live[id] {
			a, b := '1', '1'
			if n.A.Neg() {
				a = '0'
			}
			if n.B.Neg() {
				b = '0'
			}
			fmt.Fprintf(bw, ".names %s %s n%d\n%c%c 1\n", name(n.A.ID()), name(n.B.ID()), id, a, b)
		}
	}
	k := 0
	for _, p := range g.Outputs {
		for _, b := range p.Bits {
			buf(outNames[k], b)
			k++
		}
	}
	for i, l := range g.Latches {
		if liveL[i] {
			buf(fmt.Sprintf("d%d", i), l.D)
		}
	}
	fmt.Fprintf(bw, ".end\n")
	return bw.Flush()
}

// AIGER writes ASCII AIGER ("aag") with a symbol table.
func AIGER(w io.Writer, g *aig.AIG) error {
	bw := bufio.NewWriter(w)
	live := g.Live()
	liveL := g.LiveLatches()
	// renumber: inputs, live latches, live ands
	num := make([]uint32, len(g.Nodes))
	next := uint32(1)
	for _, pi := range g.PIs {
		num[pi.Node] = next
		next++
	}
	var lat []int
	for i := range g.Latches {
		if liveL[i] {
			num[g.Latches[i].Q] = next
			next++
			lat = append(lat, i)
		}
	}
	var ands []int
	for id, n := range g.Nodes {
		if n.Kind == aig.KAnd && live[id] {
			num[id] = next
			next++
			ands = append(ands, id)
		}
	}
	enc := func(l aig.Lit) uint32 {
		if l.ID() == 0 {
			return uint32(l) & 1
		}
		return num[l.ID()]<<1 | uint32(l)&1
	}
	nout := 0
	for _, p := range g.Outputs {
		nout += len(p.Bits)
	}
	fmt.Fprintf(bw, "aag %d %d %d %d %d\n", next-1, len(g.PIs), len(lat), nout, len(ands))
	for _, pi := range g.PIs {
		fmt.Fprintf(bw, "%d\n", num[pi.Node]<<1)
	}
	for _, i := range lat {
		l := g.Latches[i]
		fmt.Fprintf(bw, "%d %d %d\n", num[l.Q]<<1, enc(l.D), map[bool]int{false: 0, true: 1}[l.Init])
	}
	for _, p := range g.Outputs {
		for _, b := range p.Bits {
			fmt.Fprintf(bw, "%d\n", enc(b))
		}
	}
	for _, id := range ands {
		n := g.Nodes[id]
		fmt.Fprintf(bw, "%d %d %d\n", num[id]<<1, enc(n.A), enc(n.B))
	}
	for i, pi := range g.PIs {
		fmt.Fprintf(bw, "i%d %s\n", i, piName(g, pi))
	}
	for k, i := range lat {
		fmt.Fprintf(bw, "l%d %s\n", k, strings.ReplaceAll(g.Latches[i].Name, " ", "_"))
	}
	k := 0
	for _, p := range g.Outputs {
		for i := range p.Bits {
			n := p.Name
			if len(p.Bits) > 1 {
				n = fmt.Sprintf("%s[%d]", p.Name, i)
			}
			fmt.Fprintf(bw, "o%d %s\n", k, n)
			k++
		}
	}
	fmt.Fprintf(bw, "c\ngenerated by gatecraft\n")
	return bw.Flush()
}

var bitName = regexp.MustCompile(`^(.*)\[(\d+)\]$`)

// ReadAIGER parses ASCII AIGER (with optional latch reset values and symbols).
func ReadAIGER(r io.Reader) (*aig.AIG, error) {
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 1<<20), 1<<26)
	var lines []string
	for sc.Scan() {
		lines = append(lines, sc.Text())
	}
	if len(lines) == 0 {
		return nil, fmt.Errorf("empty AIGER file")
	}
	hdr := strings.Fields(lines[0])
	if len(hdr) < 6 || hdr[0] != "aag" {
		return nil, fmt.Errorf("not an ASCII AIGER file (expected 'aag M I L O A' header)")
	}
	var nums [5]int
	for i := range nums {
		v, err := strconv.Atoi(hdr[i+1])
		if err != nil || v < 0 {
			return nil, fmt.Errorf("bad AIGER header")
		}
		nums[i] = v
	}
	M, I, L, O, A := nums[0], nums[1], nums[2], nums[3], nums[4]
	if len(lines) < 1+I+L+O+A {
		return nil, fmt.Errorf("AIGER file truncated")
	}
	g := aig.New()
	lits := make([]aig.Lit, M+1) // AIGER var -> literal in g
	lits[0] = aig.False
	pos := 1
	field := func(s string, n int) ([]uint32, error) {
		f := strings.Fields(s)
		if len(f) < n {
			return nil, fmt.Errorf("malformed AIGER line %q", s)
		}
		out := make([]uint32, n)
		for i := 0; i < n; i++ {
			v, err := strconv.ParseUint(f[i], 10, 32)
			if err != nil {
				return nil, fmt.Errorf("malformed AIGER line %q", s)
			}
			out[i] = uint32(v)
		}
		return out, nil
	}
	type pend struct {
		cur, next uint32
		init      uint32
	}
	piNames := make([]string, I)
	for i := 0; i < I; i++ {
		f, err := field(lines[pos], 1)
		pos++
		if err != nil || f[0]&1 == 1 || int(f[0]>>1) > M {
			return nil, fmt.Errorf("bad AIGER input line")
		}
		piNames[i] = fmt.Sprintf("i%d", i)
		lits[f[0]>>1] = aig.Lit(0) // placeholder; real literal assigned after symbols
	}
	// we need symbols before creating inputs to group them; scan the symbol table first
	symStart := 1 + I + L + O + A
	inSym, latSym, outSym := map[int]string{}, map[int]string{}, map[int]string{}
	for _, ln := range lines[symStart:] {
		if ln == "c" {
			break
		}
		if len(ln) < 3 {
			continue
		}
		f := strings.SplitN(ln, " ", 2)
		if len(f) != 2 {
			continue
		}
		idx, err := strconv.Atoi(f[0][1:])
		if err != nil {
			continue
		}
		switch f[0][0] {
		case 'i':
			inSym[idx] = f[1]
		case 'l':
			latSym[idx] = f[1]
		case 'o':
			outSym[idx] = f[1]
		}
	}
	// inputs
	pos = 1
	type ibit struct {
		name string
		bit  int
	}
	inLits := make([]aig.Lit, I)
	inInfo := make([]ibit, I)
	widths := map[string]int{}
	order := []string{}
	for i := 0; i < I; i++ {
		n, ok := inSym[i]
		if !ok {
			n = fmt.Sprintf("i%d", i)
		}
		b := 0
		if m := bitName.FindStringSubmatch(n); m != nil {
			n = m[1]
			b, _ = strconv.Atoi(m[2])
		}
		if _, seen := widths[n]; !seen {
			order = append(order, n)
		}
		if b+1 > widths[n] {
			widths[n] = b + 1
		}
		inInfo[i] = ibit{n, b}
	}
	for i := 0; i < I; i++ {
		f, _ := field(lines[pos], 1)
		pos++
		l := g.AddInput(inInfo[i].name, inInfo[i].bit)
		inLits[i] = l
		lits[f[0]>>1] = l
	}
	for _, n := range order {
		p := aig.Port{Name: n, Bits: make([]aig.Lit, widths[n])}
		for i := range p.Bits {
			p.Bits[i] = aig.False
		}
		for i, ib := range inInfo {
			if ib.name == n {
				p.Bits[ib.bit] = inLits[i]
			}
		}
		g.Inputs = append(g.Inputs, p)
	}
	latches := make([]pend, L)
	for i := 0; i < L; i++ {
		ff := strings.Fields(lines[pos])
		pos++
		if len(ff) < 2 {
			return nil, fmt.Errorf("bad AIGER latch line")
		}
		f, err := field(lines[pos-1], 2)
		if err != nil {
			return nil, err
		}
		init := uint32(0)
		if len(ff) >= 3 {
			v, err := strconv.Atoi(ff[2])
			if err != nil {
				return nil, err
			}
			init = uint32(v)
		}
		latches[i] = pend{f[0], f[1], init}
		name := latSym[i]
		if name == "" {
			name = fmt.Sprintf("l%d", i)
		}
		q := g.AddLatch(name, init == 1)
		g.Latches[len(g.Latches)-1].Clock = "clk"
		lits[f[0]>>1] = q
	}
	outRefs := make([]uint32, O)
	for i := 0; i < O; i++ {
		f, err := field(lines[pos], 1)
		pos++
		if err != nil {
			return nil, err
		}
		outRefs[i] = f[0]
	}
	resolve := func(e uint32) (aig.Lit, error) {
		v := int(e >> 1)
		if v > M {
			return 0, fmt.Errorf("literal %d exceeds M", e)
		}
		return lits[v].NotIf(e&1 == 1), nil
	}
	type andDef struct{ l, a, b uint32 }
	defs := make([]andDef, A)
	for i := 0; i < A; i++ {
		f, err := field(lines[pos], 3)
		pos++
		if err != nil {
			return nil, err
		}
		defs[i] = andDef{f[0], f[1], f[2]}
	}
	// ANDs may reference later definitions in ASCII AIGER; resolve iteratively
	done := make([]bool, A)
	remaining := A
	for remaining > 0 {
		progress := false
		for i, d := range defs {
			if done[i] {
				continue
			}
			ready := func(e uint32) bool {
				v := int(e >> 1)
				if v > M {
					return false
				}
				if v == 0 {
					return true
				}
				isAnd := false
				for j := range defs {
					if int(defs[j].l>>1) == v && !done[j] {
						isAnd = true
					}
				}
				return !isAnd
			}
			if ready(d.a) && ready(d.b) {
				a, err := resolve(d.a)
				if err != nil {
					return nil, err
				}
				b, err := resolve(d.b)
				if err != nil {
					return nil, err
				}
				lits[d.l>>1] = g.And(a, b)
				done[i] = true
				remaining--
				progress = true
			}
		}
		if !progress {
			return nil, fmt.Errorf("AIGER file has a combinational cycle or undefined literal")
		}
	}
	for i, lp := range latches {
		d, err := resolve(lp.next)
		if err != nil {
			return nil, err
		}
		g.Latches[i].D = d
	}
	// outputs grouped by symbol
	outW := map[string]int{}
	outOrder := []string{}
	type obit struct {
		name string
		bit  int
	}
	oi := make([]obit, O)
	for i := 0; i < O; i++ {
		n, ok := outSym[i]
		if !ok {
			n = fmt.Sprintf("o%d", i)
		}
		b := 0
		if m := bitName.FindStringSubmatch(n); m != nil {
			n = m[1]
			b, _ = strconv.Atoi(m[2])
		}
		if _, seen := outW[n]; !seen {
			outOrder = append(outOrder, n)
		}
		if b+1 > outW[n] {
			outW[n] = b + 1
		}
		oi[i] = obit{n, b}
	}
	for _, n := range outOrder {
		p := aig.Port{Name: n, Bits: make([]aig.Lit, outW[n])}
		for i := range p.Bits {
			p.Bits[i] = aig.False
		}
		for i, ob := range oi {
			if ob.name == n {
				l, err := resolve(outRefs[i])
				if err != nil {
					return nil, err
				}
				p.Bits[ob.bit] = l
			}
		}
		g.Outputs = append(g.Outputs, p)
	}
	return g, nil
}
