// Package emit writes an AIG as structural Verilog, BLIF or ASCII AIGER, and
// reads AIGER back so external benchmark circuits can be analysed.
package emit

import (
	"bufio"
	"fmt"
	"io"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"gatecraft/internal/aig"
)

var nonIdent = regexp.MustCompile(`[^A-Za-z0-9_]`)

func ident(s string) string {
	s = nonIdent.ReplaceAllString(s, "_")
	if s == "" || (s[0] >= '0' && s[0] <= '9') {
		s = "_" + s
	}
	return s
}

// piName names an input bit.
func piName(g *aig.AIG, pi aig.PI) string {
	if p := g.FindInput(pi.Port); p != nil && len(p.Bits) > 1 {
		return fmt.Sprintf("%s[%d]", pi.Port, pi.Bit)
	}
	return pi.Port
}

// Verilog writes a structural Verilog module equivalent to g.
func Verilog(w io.Writer, g *aig.AIG, module string) error {
	bw := bufio.NewWriter(w)
	live := g.Live()
	liveL := g.LiveLatches()
	clocks := map[string]bool{}
	for i, l := range g.Latches {
		if liveL[i] {
			clocks[l.Clock] = true
		}
	}
	inputNames := map[string]bool{}
	for _, p := range g.Inputs {
		inputNames[p.Name] = true
	}
	var ports []string
	for _, p := range g.Inputs {
		ports = append(ports, decl("input", p.Name, len(p.Bits)))
	}
	for _, p := range g.Outputs {
		ports = append(ports, decl("output", p.Name, len(p.Bits)))
	}
	fmt.Fprintf(bw, "// generated by gatecraft: %s\n", g.Stats())
	fmt.Fprintf(bw, "module %s(\n  %s\n);\n", module, strings.Join(ports, ",\n  "))
	name := func(id uint32) string {
		n := g.Nodes[id]
		switch n.Kind {
		case aig.KConst:
			return "1'b0"
		case aig.KInput:
			return piName(g, g.PIs[n.Idx])
		case aig.KLatch:
			return fmt.Sprintf("r%d", n.Idx)
		}
		return fmt.Sprintf("n%d", id)
	}
	ref := func(l aig.Lit) string {
		if l == aig.False {
			return "1'b0"
		}
		if l == aig.True {
			return "1'b1"
		}
		s := name(l.ID())
		if l.Neg() {
			return "~" + s
		}
		return s
	}
	for i, l := range g.Latches {
		if liveL[i] {
			iv := 0
			if l.Init {
				iv = 1
			}
			fmt.Fprintf(bw, "  reg r%d = 1'b%d; // %s\n", i, iv, l.Name)
		}
	}
	for id, n := range g.Nodes {
		if n.Kind == aig.KAnd && live[id] {
			fmt.Fprintf(bw, "  wire n%d = %s & %s;\n", id, ref(n.A), ref(n.B))
		}
	}
	for _, p := range g.Outputs {
		for i, b := range p.Bits {
			if len(p.Bits) == 1 {
				fmt.Fprintf(bw, "  assign %s = %s;\n", p.Name, ref(b))
			} else {
				fmt.Fprintf(bw, "  assign %s[%d] = %s;\n", p.Name, i, ref(b))
			}
		}
	}
	var cs []string
	for c := range clocks {
		cs = append(cs, c)
	}
	sort.Strings(cs)
	for _, c := range cs {
		fmt.Fprintf(bw, "  always @(posedge %s) begin\n", c)
		for i, l := range g.Latches {
			if liveL[i] && l.Clock == c {
				fmt.Fprintf(bw, "    r%d <= %s;\n", i, ref(l.D))
			}
		}
		fmt.Fprintf(bw, "  end\n")
	}
	for i, p := range g.Asserts {
		fmt.Fprintf(bw, "  %s: assert property (%s);\n", ident(fmt.Sprintf("a%d_%s", i, p.Name)), ref(p.Lit))
	}
	for i, p := range g.Assumes {
		fmt.Fprintf(bw, "  %s: assume property (%s);\n", ident(fmt.Sprintf("m%d_%s", i, p.Name)), ref(p.Lit))
	}
	fmt.Fprintf(bw, "endmodule\n")
	return bw.Flush()
}

func decl(dir, name string, w int) string {
	if w == 1 {
		return fmt.Sprintf("%s %s", dir, name)
	}
	return fmt.Sprintf("%s [%d:0] %s", dir, w-1, name)
}

// BLIF writes the AIG as a BLIF network of 2-input .names plus .latch lines.
func BLIF(w io.Writer, g *aig.AIG, model string) error {
	bw := bufio.NewWriter(w)
	live := g.Live()
	liveL := g.LiveLatches()
	fmt.Fprintf(bw, ".model %s\n.inputs", model)
	for _, pi := range g.PIs {
		fmt.Fprintf(bw, " %s", piName(g, pi))
	}
	fmt.Fprintf(bw, "\n.outputs")
	outNames := []string{}
	for _, p := range g.Outputs {
		for i := range p.Bits {
			n := p.Name
			if len(p.Bits) > 1 {
				n = fmt.Sprintf("%s[%d]", p.Name, i)
			}
			outNames = append(outNames, n)
			fmt.Fprintf(bw, " %s", n)
		}
	}
	fmt.Fprintln(bw)
	name := func(id uint32) string {
		n := g.Nodes[id]
		switch n.Kind {
		case aig.KInput:
			return piName(g, g.PIs[n.Idx])
		case aig.KLatch:
			return fmt.Sprintf("r%d", n.Idx)
		case aig.KConst:
			return "zero"
		}
		return fmt.Sprintf("n%d", id)
	}
	fmt.Fprintf(bw, ".names zero\n")
	for i, l := range g.Latches {
		if liveL[i] {
			iv := 0
			if l.Init {
				iv = 1
			}
			// D is always routed through a named net for simplicity
			fmt.Fprintf(bw, ".latch d%d r%d re %s %d\n", i, i, l.Clock, iv)
		}
	}
	// a net carrying (possibly inverted) literal l
	buf := func(dst string, l aig.Lit) {
		switch l {
		case aig.False:
			fmt.Fprintf(bw, ".names %s\n", dst)
		case aig.True:
			fmt.Fprintf(bw, ".names %s\n1\n", dst)
		default:
			if l.Neg() {
				fmt.Fprintf(bw, ".names %s %s\n0 1\n", name(l.ID()), dst)
			} else {
				fmt.Fprintf(bw, ".names %s %s\n1 1\n", name(l.ID()), dst)
			}
		}
	}
	for id, n := range g.Nodes {
		if n.Kind == aig.KAnd && live[id] {
			a, b := '1', '1'
			if n.A.Neg() {
				a = '0'
			}
			if n.B.Neg() {
				b = '0'
			}
			fmt.Fprintf(bw, ".names %s %s n%d\n%c%c 1\n", name(n.A.ID()), name(n.B.ID()), id, a, b)
		}
	}
	k := 0
	for _, p := range g.Outputs {
		for _, b := range p.Bits {
			buf(outNames[k], b)
			k++
		}
	}
	for i, l := range g.Latches {
		if liveL[i] {
			buf(fmt.Sprintf("d%d", i), l.D)
		}
	}
	fmt.Fprintf(bw, ".end\n")
	return bw.Flush()
}

// AIGER writes ASCII AIGER ("aag") with a symbol table.
func AIGER(w io.Writer, g *aig.AIG) error {
	bw := bufio.NewWriter(w)
	live := g.Live()
	liveL := g.LiveLatches()
	// renumber: inputs, live latches, live ands
	num := make([]uint32, len(g.Nodes))
	next := uint32(1)
	for _, pi := range g.PIs {
		num[pi.Node] = next
		next++
	}
	var lat []int
	for i := range g.Latches {
		if liveL[i] {
			num[g.Latches[i].Q] = next
			next++
			lat = append(lat, i)
		}
	}
	var ands []int
	for id, n := range g.Nodes {
		if n.Kind == aig.KAnd && live[id] {
			num[id] = next
			next++
			ands = append(ands, id)
		}
	}
	enc := func(l aig.Lit) uint32 {
		if l.ID() == 0 {
			return uint32(l) & 1
		}
		return num[l.ID()]<<1 | uint32(l)&1
	}
	nout := 0
	for _, p := range g.Outputs {
		nout += len(p.Bits)
	}
	fmt.Fprintf(bw, "aag %d %d %d %d %d\n", next-1, len(g.PIs), len(lat), nout, len(ands))
	for _, pi := range g.PIs {
		fmt.Fprintf(bw, "%d\n", num[pi.Node]<<1)
	}
	for _, i := range lat {
		l := g.Latches[i]
		fmt.Fprintf(bw, "%d %d %d\n", num[l.Q]<<1, enc(l.D), map[bool]int{false: 0, true: 1}[l.Init])
	}
	for _, p := range g.Outputs {
		for _, b := range p.Bits {
			fmt.Fprintf(bw, "%d\n", enc(b))
		}
	}
	for _, id := range ands {
		n := g.Nodes[id]
		fmt.Fprintf(bw, "%d %d %d\n", num[id]<<1, enc(n.A), enc(n.B))
	}
	for i, pi := range g.PIs {
		fmt.Fprintf(bw, "i%d %s\n", i, piName(g, pi))
	}
	for k, i := range lat {
		fmt.Fprintf(bw, "l%d %s\n", k, strings.ReplaceAll(g.Latches[i].Name, " ", "_"))
	}
	k := 0
	for _, p := range g.Outputs {
		for i := range p.Bits {
			n := p.Name
			if len(p.Bits) > 1 {
				n = fmt.Sprintf("%s[%d]", p.Name, i)
			}
			fmt.Fprintf(bw, "o%d %s\n", k, n)
			k++
		}
	}
	fmt.Fprintf(bw, "c\ngenerated by gatecraft\n")
	return bw.Flush()
}

var bitName = regexp.MustCompile(`^(.*)\[(\d+)\]$`)

// splitBit turns "name[3]" into ("name", 3); plain names are bit 0 of a 1-bit port.
func splitBit(sym string) (string, int) {
	if m := bitName.FindStringSubmatch(sym); m != nil {
		b, _ := strconv.Atoi(m[2])
		return m[1], b
	}
	return sym, 0
}

// ReadAIGER parses ASCII AIGER (with optional latch reset values and a symbol table).
// Bit symbols like "a[3]" are regrouped into multi-bit ports; every latch is
// clocked by an implicit clock named "clk".
func ReadAIGER(r io.Reader) (*aig.AIG, error) {
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 1<<20), 1<<26)
	var lines []string
	for sc.Scan() {
		lines = append(lines, sc.Text())
	}
	if len(lines) == 0 {
		return nil, fmt.Errorf("empty AIGER file")
	}
	hdr := strings.Fields(lines[0])
	if len(hdr) < 6 || hdr[0] != "aag" {
		return nil, fmt.Errorf("not an ASCII AIGER file (expected 'aag M I L O A' header)")
	}
	var h [5]int
	for i := range h {
		v, err := strconv.Atoi(hdr[i+1])
		if err != nil || v < 0 {
			return nil, fmt.Errorf("bad AIGER header")
		}
		h[i] = v
	}
	M, I, L, O, A := h[0], h[1], h[2], h[3], h[4]
	if len(lines) < 1+I+L+O+A {
		return nil, fmt.Errorf("AIGER file truncated")
	}
	nums := func(line string, n int) ([]uint32, error) {
		f := strings.Fields(line)
		if len(f) < n {
			return nil, fmt.Errorf("malformed AIGER line %q", line)
		}
		out := make([]uint32, n)
		for i := range out {
			v, err := strconv.ParseUint(f[i], 10, 32)
			if err != nil {
				return nil, fmt.Errorf("malformed AIGER line %q", line)
			}
			if int(v>>1) > M {
				return nil, fmt.Errorf("AIGER literal %d exceeds the maximum variable index %d", v, M)
			}
			out[i] = uint32(v)
		}
		return out, nil
	}

	// symbol table (after the AND section)
	sym := map[byte]map[int]string{'i': {}, 'l': {}, 'o': {}}
	for _, ln := range lines[1+I+L+O+A:] {
		if ln == "c" {
			break
		}
		f := strings.SplitN(ln, " ", 2)
		if len(f) != 2 || len(f[0]) < 2 || sym[f[0][0]] == nil {
			continue
		}
		if idx, err := strconv.Atoi(f[0][1:]); err == nil {
			sym[f[0][0]][idx] = f[1]
		}
	}

	g := aig.New()
	lits := make([]aig.Lit, M+1) // AIGER variable -> literal in g
	pos := 1

	// inputs
	var inPorts []aig.Port
	inIdx := map[string]int{}
	for i := 0; i < I; i++ {
		f, err := nums(lines[pos], 1)
		pos++
		if err != nil {
			return nil, err
		}
		if f[0]&1 == 1 || f[0] == 0 {
			return nil, fmt.Errorf("bad AIGER input literal %d", f[0])
		}
		name, b := splitBit(orDefault(sym['i'][i], fmt.Sprintf("i%d", i)))
		l := g.AddInput(name, b)
		lits[f[0]>>1] = l
		pi, ok := inIdx[name]
		if !ok {
			pi = len(inPorts)
			inIdx[name] = pi
			inPorts = append(inPorts, aig.Port{Name: name})
		}
		for len(inPorts[pi].Bits) <= b {
			inPorts[pi].Bits = append(inPorts[pi].Bits, aig.False)
		}
		inPorts[pi].Bits[b] = l
	}
	g.Inputs = inPorts

	// latches
	var nexts []uint32
	for i := 0; i < L; i++ {
		f, err := nums(lines[pos], 2)
		pos++
		if err != nil {
			return nil, err
		}
		init := false
		if ff := strings.Fields(lines[pos-1]); len(ff) >= 3 {
			switch ff[2] {
			case "0":
			case "1":
				init = true
			default:
				return nil, fmt.Errorf("unsupported latch reset value %q (only 0 and 1)", ff[2])
			}
		}
		q := g.AddLatch(orDefault(sym['l'][i], fmt.Sprintf("l%d", i)), init)
		g.Latches[len(g.Latches)-1].Clock = "clk"
		lits[f[0]>>1] = q
		nexts = append(nexts, f[1])
	}

	// outputs (resolved after the ANDs exist)
	outRefs := make([]uint32, O)
	for i := range outRefs {
		f, err := nums(lines[pos], 1)
		pos++
		if err != nil {
			return nil, err
		}
		outRefs[i] = f[0]
	}

	// AND gates may reference later definitions in ASCII AIGER: resolve on demand
	type andDef struct{ a, b uint32 }
	defs := map[int]andDef{}
	for i := 0; i < A; i++ {
		f, err := nums(lines[pos], 3)
		pos++
		if err != nil {
			return nil, err
		}
		if f[0]&1 == 1 || f[0] == 0 {
			return nil, fmt.Errorf("bad AIGER AND literal %d", f[0])
		}
		defs[int(f[0]>>1)] = andDef{f[1], f[2]}
	}
	const inProgress = aig.Lit(0xFFFFFFFE)
	var build func(v int) (aig.Lit, error)
	build = func(v int) (aig.Lit, error) {
		if v == 0 {
			return aig.False, nil
		}
		switch lits[v] {
		case inProgress:
			return 0, fmt.Errorf("AIGER file has a combinational cycle through variable %d", v)
		case 0:
			d, ok := defs[v]
			if !ok {
				return 0, fmt.Errorf("AIGER variable %d is used but never defined", v)
			}
			lits[v] = inProgress
			a, err := build(int(d.a >> 1))
			if err != nil {
				return 0, err
			}
			b, err := build(int(d.b >> 1))
			if err != nil {
				return 0, err
			}
			lits[v] = g.And(a.NotIf(d.a&1 == 1), b.NotIf(d.b&1 == 1))
		}
		return lits[v], nil
	}
	resolve := func(e uint32) (aig.Lit, error) {
		l, err := build(int(e >> 1))
		return l.NotIf(e&1 == 1), err
	}
	for i, n := range nexts {
		d, err := resolve(n)
		if err != nil {
			return nil, err
		}
		g.Latches[i].D = d
	}
	var outPorts []aig.Port
	outIdx := map[string]int{}
	for i, ref := range outRefs {
		l, err := resolve(ref)
		if err != nil {
			return nil, err
		}
		name, b := splitBit(orDefault(sym['o'][i], fmt.Sprintf("o%d", i)))
		pi, ok := outIdx[name]
		if !ok {
			pi = len(outPorts)
			outIdx[name] = pi
			outPorts = append(outPorts, aig.Port{Name: name})
		}
		for len(outPorts[pi].Bits) <= b {
			outPorts[pi].Bits = append(outPorts[pi].Bits, aig.False)
		}
		outPorts[pi].Bits[b] = l
	}
	g.Outputs = outPorts
	return g, nil
}

func orDefault(s, d string) string {
	if s == "" {
		return d
	}
	return s
}
