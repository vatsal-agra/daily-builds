MAX_CODE_LENGTH = 16


class _Node:
    __slots__ = ("freq", "order", "symbol", "left", "right")

    def __init__(self, freq, order, symbol=None, left=None, right=None):
        self.freq = freq
        self.order = order  # tie-break for a deterministic heap order
        self.symbol = symbol
        self.left = left
        self.right = right

    def __lt__(self, other):
        if self.freq != other.freq:
            return self.freq < other.freq
        return self.order < other.order


def _huffman_tree_lengths(freqs):
    """Build a standard (unlimited-height) Huffman tree from a
    {symbol: frequency} map and return {symbol: code_length}.
    Handles the 0- and 1-symbol degenerate cases explicitly.
    """
    symbols = [s for s, f in freqs.items() if f > 0]
    if not symbols:
        return {}
    if len(symbols) == 1:
        return {symbols[0]: 1}

    heap = []
    order = 0
    for s in symbols:
        heapq.heappush(heap, _Node(freqs[s], order, symbol=s))
        order += 1
    while len(heap) > 1:
        a = heapq.heappop(heap)
        b = heapq.heappop(heap)
        heapq.heappush(heap, _Node(a.freq + b.freq, order, left=a, right=b))
        order += 1
    root = heap[0]

    lengths = {}

    def walk(node, depth):
        if node.symbol is not None:
            lengths[node.symbol] = depth
            return
        walk(node.left, depth + 1)
        walk(node.right, depth + 1)

    walk(root, 0)
    return lengths


def optimize_table(freqs, fallback_bits, fallback_values):
    """Build a real canonical Huffman table from measured frequencies.

    Falls back to the standard Annex-K table of matching kind if the
    resulting tree would need codes longer than JPEG's 16-bit limit --
    which requires a frequency distribution shaped like consecutive
    Fibonacci numbers to trigger (the classic worst case for Huffman
    code depth) and essentially never happens for real DCT-coefficient
    statistics, but is a real, reachable path that is unit-tested with
    exactly such an adversarial distribution rather than just assumed
    safe.
    """
    lengths = _huffman_tree_lengths(freqs)
    if not lengths or max(lengths.values()) > MAX_CODE_LENGTH:
        return HuffmanTable(fallback_bits, fallback_values), False

    max_len = max(lengths.values())
    bits = [0] * max_len
    for length in lengths.values():
        bits[length - 1] += 1

    # HUFFVAL order within a length must be consistent with the code
    # assignment order (ascending) -- any fixed deterministic order works
    # as long as encoder and decoder agree, so sort by (length, symbol).
    values = [sym for sym, _ in sorted(lengths.items(), key=lambda kv: (kv[1], kv[0]))]

    if len(bits) < MAX_CODE_LENGTH:
        bits = bits + [0] * (MAX_CODE_LENGTH - len(bits))

    return HuffmanTable(bits, values), True
