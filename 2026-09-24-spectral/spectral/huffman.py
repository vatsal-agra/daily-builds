"""Canonical Huffman tables for JPEG entropy coding.

JPEG never ships a Huffman *tree* in the file -- it ships a canonical
representation: BITS[1..16] (how many codes have each length) and
HUFFVAL[] (the symbols in code order). The actual bit patterns are
regenerated by both encoder and decoder from that representation using
the fixed procedure in ITU-T T.81 Annex C, which assigns codes of a given
length consecutively and in increasing order -- that's what "canonical"
means, and it's why the table only needs lengths + symbol order, not full
codes, to travel in the file.

This module provides:
  * the four ITU-T T.81 Annex K standard tables (DC/AC x luma/chroma)
  * `build_codes` -- Annex C's BITS/HUFFVAL -> {symbol: (code, length)}
  * `HuffmanTable` -- wraps a code map with an encoder and a decoder
  * `optimize_table` -- builds a real per-image canonical table from
    measured symbol frequencies (a proper Huffman tree via a min-heap),
    with a tested fallback to the matching standard table for the
    (practically unreachable for real image statistics, but real and
    checked-for) pathological case where the resulting tree would need
    codes longer than JPEG's 16-bit limit
"""
