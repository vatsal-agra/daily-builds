def build_codes(bits, values):
    """ITU-T T.81 Annex C.2: BITS/HUFFVAL -> {symbol: (code, length)}.

    Codes of a given length are assigned consecutively, in the order the
    symbols for that length appear in HUFFVAL; when the length increases
    the running code is shifted left one bit. This is the exact
    canonical-code generation procedure, implemented directly from the
    spec's Generate_size_table / Generate_code_table pseudocode.
    """
    huffsize = []
    for length, count in enumerate(bits, start=1):
        huffsize.extend([length] * count)

    huffcode = []
    code = 0
    si = huffsize[0] if huffsize else 0
    k = 0
    while k < len(huffsize):
        while k < len(huffsize) and huffsize[k] == si:
            huffcode.append(code)
            code += 1
            k += 1
        code <<= 1
        si += 1

    table = {}
    for val, length, code in zip(values, huffsize, huffcode):
        table[val] = (code, length)
    return table


class HuffmanTable:
    """A canonical Huffman table usable for both encoding and decoding."""

    def __init__(self, bits, values):
        self.bits = list(bits)
        self.values = list(values)
        self.encode_map = build_codes(self.bits, self.values)
        # decode_map[(length, code)] = symbol, for bit-by-bit decoding.
        self.decode_map = {
            (length, code): sym for sym, (code, length) in self.encode_map.items()
        }
        self.max_code_length = max((l for _, l in self.encode_map.values()), default=0)

    def encode_symbol(self, writer, symbol):
        code, length = self.encode_map[symbol]
        writer.write_bits(code, length)

    def decode_symbol(self, reader):
        """Read bits one at a time (canonical decode) until a valid code
        of some length matches; returns the symbol, or None on EOF/marker.
        """
        code = 0
        for length in range(1, self.max_code_length + 1):
            bit = reader.read_bit()
            if bit is None:
                return None
            code = (code << 1) | bit
            sym = self.decode_map.get((length, code))
            if sym is not None:
                return sym
        return None

    def as_marker_bytes(self):
        """The BITS(16) + HUFFVAL(n) payload used inside a DHT segment."""
        return bytes(self.bits) + bytes(self.values)


