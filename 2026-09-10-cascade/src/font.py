def glyph_for(ch):
    up = ch.upper()
    return _FONT.get(up)


def measure_text(text, font_size):
    return len(text) * font_size * CHAR_WIDTH_RATIO


def char_advance(font_size):
    return font_size * CHAR_WIDTH_RATIO


def line_height_for(font_size, declared="normal"):
    if declared in (None, "normal", ""):
        return font_size * LINE_HEIGHT_RATIO
    try:
        if declared.endswith("px"):
            return float(declared[:-2])
        return float(declared) * font_size
    except ValueError:
        return font_size * LINE_HEIGHT_RATIO
