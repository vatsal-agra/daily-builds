package sp

import (
	"fmt"
	"math/rand"
	"strings"
)

// GenConfig shapes random program generation.
type GenConfig struct {
	Vars    int  // long-lived variables (register pressure)
	Depth   int  // maximum nesting of if/loop
	Stmts   int  // statements per straight-line region
	Shuffle bool // randomly permute block layout (entry stays first)
}

// DefaultGen is a moderate configuration.
var DefaultGen = GenConfig{Vars: 10, Depth: 3, Stmts: 6}

type gen struct {
	r      *rand.Rand
	cfg    GenConfig
	sb     strings.Builder
	label  int
	temp   int
	vars   []string
	budget int
}

var genBin = []string{"add", "sub", "mul", "and", "or", "xor", "shl", "shr", "lt", "le", "eq", "ne", "div", "rem"}

func (g *gen) v() string { return g.vars[g.r.Intn(len(g.vars))] }
func (g *gen) operand() string {
	if g.r.Intn(4) == 0 {
		return fmt.Sprint(g.r.Intn(41) - 10)
	}
	return g.v()
}
func (g *gen) fresh(p string) string { g.temp++; return fmt.Sprintf("%s%d", p, g.temp) }
func (g *gen) lbl(p string) string   { g.label++; return fmt.Sprintf("%s%d", p, g.label) }
func (g *gen) emit(f string, a ...any) {
	g.sb.WriteString("  " + fmt.Sprintf(f, a...) + "\n")
}

func (g *gen) stmt() {
	g.budget--
	switch k := g.r.Intn(12); {
	case k < 5:
		op := genBin[g.r.Intn(len(genBin))]
		b := g.operand()
		if op == "shl" || op == "shr" {
			b = fmt.Sprint(g.r.Intn(8))
		}
		g.emit("%s = %s %s, %s", g.v(), op, g.v(), b)
	case k < 7:
		g.emit("%s = mov %s", g.v(), g.v())
	case k == 7:
		g.emit("%s = load %s", g.v(), g.v())
	case k == 8:
		g.emit("store %s, %s", g.v(), g.operand())
	case k == 9:
		g.emit("print %s", g.v())
	case k == 10:
		// short-lived temporaries: more live-range variety
		t1, t2 := g.fresh("t"), g.fresh("t")
		g.emit("%s = add %s, %s", t1, g.v(), g.operand())
		g.emit("%s = mul %s, %s", t2, t1, g.v())
		g.emit("%s = xor %s, %s", g.v(), t2, t1)
	default:
		g.emit("%s = const %d", g.v(), g.r.Intn(2000)-1000)
	}
}

func (g *gen) region(depth int) {
	n := 1 + g.r.Intn(g.cfg.Stmts)
	for i := 0; i < n && g.budget > 0; i++ {
		if depth > 0 && g.r.Intn(4) == 0 {
			if g.r.Intn(2) == 0 {
				g.ifElse(depth - 1)
			} else {
				g.loop(depth - 1)
			}
			continue
		}
		g.stmt()
	}
}

func (g *gen) ifElse(depth int) {
	th, el, jn := g.lbl("then"), g.lbl("else"), g.lbl("join")
	c := g.fresh("c")
	g.emit("%s = %s %s, %s", c, []string{"lt", "eq", "ne", "le"}[g.r.Intn(4)], g.v(), g.operand())
	g.emit("br %s, %s, %s", c, th, el)
	g.sb.WriteString(th + ":\n")
	g.region(depth)
	g.emit("jmp %s", jn)
	g.sb.WriteString(el + ":\n")
	g.region(depth)
	g.emit("jmp %s", jn)
	g.sb.WriteString(jn + ":\n")
}

func (g *gen) loop(depth int) {
	head, body, exit := g.lbl("head"), g.lbl("body"), g.lbl("exit")
	k, bound := g.fresh("k"), g.fresh("bound")
	g.emit("%s = const 0", k)
	g.emit("%s = and %s, 3", bound, g.v())
	g.emit("%s = add %s, 2", bound, bound)
	g.emit("jmp %s", head)
	g.sb.WriteString(head + ":\n")
	c := g.fresh("c")
	g.emit("%s = lt %s, %s", c, k, bound)
	g.emit("br %s, %s, %s", c, body, exit)
	g.sb.WriteString(body + ":\n")
	g.region(depth)
	g.emit("%s = add %s, 1", k, k)
	g.emit("jmp %s", head)
	g.sb.WriteString(exit + ":\n")
}

// Generate builds a random, terminating, well-formed program as IR text.
func Generate(seed int64, cfg GenConfig) string {
	if cfg.Vars < 2 {
		cfg.Vars = 2
	}
	if cfg.Stmts < 1 {
		cfg.Stmts = 1
	}
	g := &gen{r: rand.New(rand.NewSource(seed)), cfg: cfg, budget: 400}
	for i := 0; i < cfg.Vars; i++ {
		g.vars = append(g.vars, fmt.Sprintf("v%d", i))
	}
	fmt.Fprintf(&g.sb, "; generated by spillway gen -seed %d -vars %d -depth %d\nfunc gen%d(2) {\nentry:\n", seed, cfg.Vars, cfg.Depth, seed)
	for i, v := range g.vars {
		if i < 2 {
			g.emit("%s = arg %d", v, i)
		} else if g.r.Intn(3) == 0 {
			g.emit("%s = add %s, %d", v, g.vars[g.r.Intn(i)], g.r.Intn(9)+1)
		} else {
			g.emit("%s = const %d", v, g.r.Intn(200)-50)
		}
	}
	g.region(cfg.Depth)
	g.region(cfg.Depth)
	g.emit("sum = const 0")
	for _, v := range g.vars {
		g.emit("sum = add sum, %s", v)
		g.emit("sum = xor sum, %s", v)
	}
	g.emit("print sum")
	g.emit("ret sum")
	g.sb.WriteString("}\n")
	text := g.sb.String()
	if cfg.Shuffle {
		text = shuffleBlocks(text, g.r)
	}
	return text
}

// shuffleBlocks randomly permutes every block except the entry. Because the
// generator terminates every block explicitly, layout order cannot change the
// program's meaning — but it does change linear-scan numbering, which is
// exactly what we want to stress.
func shuffleBlocks(text string, r *rand.Rand) string {
	lines := strings.Split(strings.TrimRight(text, "\n"), "\n")
	var head, tail []string
	var blocks [][]string
	for _, ln := range lines {
		switch {
		case strings.HasPrefix(ln, "}"):
			tail = append(tail, ln)
		case strings.HasSuffix(ln, ":") && !strings.HasPrefix(ln, " "):
			blocks = append(blocks, []string{ln})
		case len(blocks) == 0:
			head = append(head, ln)
		default:
			blocks[len(blocks)-1] = append(blocks[len(blocks)-1], ln)
		}
	}
	rest := blocks[1:]
	r.Shuffle(len(rest), func(i, j int) { rest[i], rest[j] = rest[j], rest[i] })
	out := append([]string(nil), head...)
	for _, b := range blocks {
		out = append(out, b...)
	}
	out = append(out, tail...)
	return strings.Join(out, "\n") + "\n"
}
